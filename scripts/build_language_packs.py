#!/usr/bin/env python3
"""Build the three uploadable, single-language distributions from shared source."""
import gzip
import hashlib
import io
import json
from pathlib import Path
import re
import tarfile

ROOT = Path(__file__).resolve().parents[1]
REPOSITORY = "raimondarias/pterodactyl-installer"
LANGUAGES = {"en": "English", "es": "Español", "pt-BR": "Português (Brasil)"}


def encoded(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode()


def build(output=None):
    output = Path(output) if output else ROOT / "languages"
    version = re.search(r'__version__ = "([^"]+)"', (ROOT / "ptero/__init__.py").read_text())[1]
    if f'VERSION="{version}"' not in (ROOT / "install.sh").read_text():
        raise ValueError("Bootstrap and runtime versions differ")
    catalogue = json.loads((ROOT / "ptero/locales/messages.json").read_text())
    locales = {language: encoded({source: {language: translations[language]}
                                 for source, translations in catalogue.items()}) for language in LANGUAGES}
    hashes = {language: hashlib.sha256(data).hexdigest() for language, data in locales.items()}
    files = {str(path.relative_to(ROOT)): path.read_bytes() for path in (ROOT / "ptero").rglob("*")
             if path.is_file() and "__pycache__" not in path.parts and path.suffix in (".py", ".json")
             and path.name not in ("messages.json", "distribution.json")}
    for name in ("installer.py", "scripts/run_local.sh", "LICENSE"):
        files[name] = (ROOT / name).read_bytes()
    for language, label in LANGUAGES.items():
        directory = output / language
        directory.mkdir(parents=True, exist_ok=True)
        metadata = {"schema": 1, "repository": REPOSITORY, "language": language, "version": version,
                    "locale_sha256": hashes}
        content = {**files, "ptero/locales/messages.json": locales[language],
                   "ptero/distribution.json": encoded(metadata)}
        memory = io.BytesIO()
        # Stable metadata makes rebuilding unchanged source byte-for-byte reproducible.
        with gzip.GzipFile(fileobj=memory, mode="wb", mtime=0) as compressed:
            with tarfile.open(fileobj=compressed, mode="w") as archive:
                for name, data in sorted(content.items()):
                    item = tarfile.TarInfo(name)
                    item.size, item.mode, item.mtime = len(data), 0o644, 0
                    archive.addfile(item, io.BytesIO(data))
        payload = memory.getvalue()
        digest = hashlib.sha256(payload).hexdigest()
        (directory / "installer.tar.gz").write_bytes(payload)
        (directory / "installer.tar.gz.sha256").write_text(digest + "  installer.tar.gz\n")
        (directory / "messages.json").write_bytes(locales[language])
        (directory / "manifest.json").write_bytes(encoded({**metadata, "archive_sha256": digest}))
        (directory / "README.md").write_text(
            f"# {label} installer package\n\n"
            f"Generated by `python3 scripts/build_language_packs.py` for version **{version}**.\n\n"
            "Upload this entire directory. The root bootstrap downloads this language's archive and checksum "
            "after selection. The archive contains the shared installer code and only this language's catalogue. "
            "`messages.json` is also used when changing language from the running menu.\n\n"
            "Edit the maintained translation tables in `scripts/`, then rebuild all packages. "
            "Do not edit a generated archive or manifest by hand.\n")
        print(f"{directory.relative_to(output.parent)}: {len(payload):,} bytes ({digest[:12]})")
    return output


if __name__ == "__main__":
    build()
